"""The SQLite-to-Postgres statement translator of the Postgres plugin's compatibility layer."""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

_PATH = Path(__file__).resolve().parents[1] / "postgres" / "compat" / "translate.py"
_spec = importlib.util.spec_from_file_location("hermes_compat_translate", _PATH)
translate_module = importlib.util.module_from_spec(_spec)
sys.modules[_spec.name] = translate_module
_spec.loader.exec_module(translate_module)


def pg(sql: str) -> str:
    return translate_module.translate(sql, param_style=lambda token: "%s").sql


def squash(text: str) -> str:
    return " ".join(text.split())


@pytest.mark.parametrize("sql, expected", [
    ("SELECT * FROM t WHERE id=?", "SELECT * FROM t WHERE id=%s"),
    ("SELECT * FROM t WHERE a IS ? AND b IS NOT ? AND c IS NULL AND d IS NOT NULL",
     "SELECT * FROM t WHERE a IS NOT DISTINCT FROM %s AND b IS DISTINCT FROM %s AND c IS NULL AND d IS NOT NULL"),
    ("SELECT x FROM t WHERE name LIKE ?", "SELECT x FROM t WHERE name ILIKE %s"),
    ("SELECT ifnull(a, 0), max(a, b), max(c) FROM t", "SELECT coalesce(a, 0), greatest(a, b), max(c) FROM t"),
    ("SELECT * FROM t LIMIT -1 OFFSET ?", "SELECT * FROM t LIMIT ALL OFFSET %s"),
    ("SELECT '50% off ?' FROM t", "SELECT '50%% off ?' FROM t"),
    ("SELECT julianday(x), datetime('now') FROM t", "SELECT hermes_julianday(x), hermes_datetime('now') FROM t"),
])
def test_expressions(sql, expected):
    assert squash(pg(sql)) == expected


def test_order_by_terms_get_sqlite_null_placement_once_each():
    out = squash(pg("SELECT * FROM t ORDER BY a DESC, b, c NULLS LAST LIMIT 5"))
    assert out == "SELECT * FROM t ORDER BY a DESC NULLS LAST , b NULLS FIRST , c NULLS LAST LIMIT 5"


def test_window_order_by_ends_at_its_parenthesis():
    out = squash(pg("SELECT row_number() OVER (PARTITION BY j ORDER BY k DESC) FROM t"))
    assert out == "SELECT row_number() OVER (PARTITION BY j ORDER BY k DESC NULLS LAST ) FROM t"


def test_insert_or_ignore_and_replace():
    assert squash(pg("INSERT OR IGNORE INTO t (a) VALUES (?)")) == "INSERT INTO t (a) VALUES (%s) ON CONFLICT DO NOTHING"
    stmt = translate_module.translate("REPLACE INTO t (a, b) VALUES (?, ?)", param_style=lambda token: "%s")
    assert stmt.insert_or_replace and stmt.table == "t" and stmt.replace_columns == ["a", "b"]
    assert "{target}" in stmt.sql


def test_create_table_types_and_options():
    stmt = translate_module.translate(
        "CREATE TABLE IF NOT EXISTS t (id INTEGER PRIMARY KEY AUTOINCREMENT, date TEXT, n INTEGER NOT NULL, "
        "r REAL, b BLOB, v VARCHAR(64), ts DATETIME DEFAULT CURRENT_TIMESTAMP, CHECK (n > 0)) WITHOUT ROWID",
        param_style=lambda token: "%s")
    out = squash(stmt.sql)
    assert "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in out
    assert "date TEXT" in out and "n bigint NOT NULL" in out and "r double precision" in out and "b bytea" in out
    assert "v text" in out and "(64)" not in out and "WITHOUT" not in out and "ROWID" not in out
    assert "to_char(now() AT TIME ZONE 'UTC'" in out
    assert stmt.kind == "CREATE TABLE" and stmt.table == "t" and stmt.ddl.startswith("CREATE TABLE IF NOT EXISTS t")


def test_create_index_names_its_table():
    stmt = translate_module.translate("CREATE INDEX IF NOT EXISTS i ON t(a, b DESC)", param_style=lambda token: "%s")
    assert (stmt.kind, stmt.table, stmt.tbl_name) == ("CREATE INDEX", "i", "t")


def test_alter_add_column_maps_its_type():
    stmt = translate_module.translate("ALTER TABLE t ADD COLUMN flag INTEGER NOT NULL DEFAULT 0", param_style=lambda token: "%s")
    assert stmt.kind == "ALTER ADD" and stmt.add_column == "flag"
    assert squash(stmt.sql) == "ALTER TABLE t ADD COLUMN flag bigint NOT NULL DEFAULT 0"


def test_transaction_control_and_pragma():
    assert translate_module.translate("BEGIN IMMEDIATE", param_style=str).kind == "BEGIN"
    assert translate_module.translate("END", param_style=str).kind == "COMMIT"
    stmt = translate_module.translate("PRAGMA table_info(executions)", param_style=str)
    assert stmt.kind == "PRAGMA" and stmt.pragma == ("table_info", "executions")


def test_script_split_keeps_strings_whole():
    parts = translate_module.split_statements("CREATE TABLE a (x TEXT DEFAULT ';'); INSERT INTO a VALUES ('b;c');")
    assert parts == ["CREATE TABLE a (x TEXT DEFAULT ';')", "INSERT INTO a VALUES ('b;c')"]


def test_untyped_columns_become_text():
    rowid = ", rowid bigint GENERATED BY DEFAULT AS IDENTITY)"
    assert squash(pg("CREATE TABLE t (x)")) == "CREATE TABLE t (x text" + rowid
    assert squash(pg("CREATE TABLE t (k PRIMARY KEY, v NOT NULL)")) == "CREATE TABLE t (k text PRIMARY KEY, v text NOT NULL" + rowid


def test_casts_use_postgres_types():
    assert squash(pg("SELECT SUM(LENGTH(CAST(key AS BLOB))) FROM t")) == "SELECT SUM(LENGTH(hermes_blob(key ))) FROM t"
    assert squash(pg("SELECT CAST(x AS INTEGER), CAST(y AS REAL), CAST(z AS TEXT) FROM t")) == \
        "SELECT CAST(x AS bigint), CAST(y AS double precision), CAST(z AS TEXT) FROM t"


def test_tables_get_sqlite_rowid():
    assert squash(pg("CREATE TABLE t (k TEXT PRIMARY KEY, v TEXT)")).endswith(
        "v TEXT, rowid bigint GENERATED BY DEFAULT AS IDENTITY)")
    assert squash(pg("CREATE TABLE t (id INTEGER PRIMARY KEY, v TEXT)")).endswith(
        'v TEXT, rowid bigint GENERATED ALWAYS AS ("id") STORED)')


def test_positional_values_get_a_column_list_slot():
    assert squash(pg("INSERT OR IGNORE INTO t VALUES (?, ?) RETURNING k")) == \
        "INSERT INTO t {columns} VALUES (%s, %s) ON CONFLICT DO NOTHING RETURNING k"
    assert squash(pg("INSERT INTO t (a) VALUES (?)")) == "INSERT INTO t (a) VALUES (%s)"


def test_upsert_update_columns_name_the_existing_row():
    out = squash(pg("INSERT INTO agg (k, value) VALUES (?, ?) ON CONFLICT(k) DO UPDATE SET value = value + excluded.value, "
                    "n = coalesce(n, 0) + 1 WHERE value < 10 RETURNING value"))
    assert out.endswith("DO UPDATE SET value = agg.value + excluded.value, n = coalesce(agg.n, 0) + 1 "
                        "WHERE agg.value < 10 RETURNING value")


@pytest.mark.parametrize("sql, expected", [
    ("SELECT 1 FROM t WHERE a IS NULL AND 1 AND EXISTS (SELECT 1 FROM u)",
     "SELECT 1 FROM t WHERE a IS NULL AND hermes_truthy( 1 ) AND EXISTS (SELECT 1 FROM u)"),
    ("SELECT CASE WHEN json_valid(d) THEN d END FROM t",
     "SELECT CASE WHEN hermes_truthy( hermes_json_valid(d) ) THEN d END FROM t"),
    ("SELECT CASE k WHEN 1 THEN 'a' END FROM t", "SELECT CASE k WHEN 1 THEN 'a' END FROM t"),
    ("SELECT * FROM t WHERE n BETWEEN 1 AND 5 AND flag", "SELECT * FROM t WHERE n BETWEEN 1 AND 5 AND hermes_truthy( flag )"),
    ("SELECT * FROM t WHERE (flag OR x = 1) AND NOT done", "SELECT * FROM t WHERE ( hermes_truthy( flag ) OR x = 1) AND NOT hermes_truthy( done )"),
    ("SELECT * FROM t WHERE a NOT IN (1, 2) AND b IS NOT NULL", "SELECT * FROM t WHERE a NOT IN (1, 2) AND b IS NOT NULL"),
    ("SELECT * FROM t JOIN u ON t.k = u.k WHERE u.v", "SELECT * FROM t JOIN u ON t.k = u.k WHERE hermes_truthy( u.v )"),
])
def test_conditions_take_sqlite_truthiness(sql, expected):
    assert pg(sql).replace(" ", "") == expected.replace(" ", "")


def test_postgres_reserved_names_are_quoted():
    assert squash(pg("CREATE TABLE l (id TEXT, grant TEXT NOT NULL)")).startswith('CREATE TABLE l (id TEXT, "grant" TEXT NOT NULL')
    assert squash(pg("SELECT grant, user FROM l")) == 'SELECT "grant", "user" FROM l'


def test_parameters_tested_for_null_are_typed():
    assert squash(pg("UPDATE t SET a = 1 WHERE (? IS NULL OR b = ?) AND ? IS NOT NULL AND c IS NULL")) == \
        "UPDATE t SET a = 1 WHERE (%s::text IS NULL OR b = %s) AND %s::text IS NOT NULL AND c IS NULL"


def test_update_or_ignore_marks_its_where_clause():
    stmt = translate_module.translate("UPDATE OR IGNORE subs SET chat = ? WHERE platform = ? AND chat IN (?, ?)",
                                      param_style=lambda token: "%s")
    assert (stmt.kind, stmt.update_or, stmt.table) == ("UPDATE", "IGNORE", "subs")
    head, marker, where = stmt.sql.partition("/*hermes_where*/")
    assert marker and squash(head) == "UPDATE subs SET chat = %s" and squash(where).startswith("WHERE platform = %s")


def test_connection_counters_are_placeholders():
    assert squash(pg("SELECT last_insert_rowid(), changes()")) == "SELECT {last_insert_rowid}, {changes}"


def test_add_column_keeps_its_sqlite_text():
    stmt = translate_module.translate("ALTER TABLE t ADD COLUMN note TEXT NOT NULL DEFAULT 'x';", param_style=str)
    assert stmt.ddl == "note TEXT NOT NULL DEFAULT 'x'"
